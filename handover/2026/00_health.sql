-- Health gate: one row. Blocks on problems in the MECL snapshot area or on the three platform refresh tasks.
-- (Feed view names never appear in PLATFORM_HEALTH, so they are not part of the gate.)
SELECT
  YEAR(CONVERT_TIMEZONE('Europe/Berlin', CURRENT_TIMESTAMP())) AS BASE_YEAR,
  (SELECT COUNT(*)
     FROM MECL_PLATFORM.ANALYTICS.PLATFORM_HEALTH
    WHERE IS_PROBLEM
      AND (AREA = 'MECL_SNAPSHOT'
           OR OBJECT_NAME IN ('TASK_REFRESH_PURCHASING', 'TASK_REFRESH_SUPPLY_CHAIN', 'TASK_REFRESH_PLATFORM_HEALTH'))) AS PROBLEM_COUNT,
  (SELECT LISTAGG(COALESCE(AREA, '?') || '/' || COALESCE(OBJECT_NAME, '?') || ':' || COALESCE(STATUS, '?'), ', ')
          WITHIN GROUP (ORDER BY AREA, OBJECT_NAME)
     FROM MECL_PLATFORM.ANALYTICS.PLATFORM_HEALTH
    WHERE IS_PROBLEM
      AND (AREA = 'MECL_SNAPSHOT'
           OR OBJECT_NAME IN ('TASK_REFRESH_PURCHASING', 'TASK_REFRESH_SUPPLY_CHAIN', 'TASK_REFRESH_PLATFORM_HEALTH'))) AS PROBLEM_LIST,
  (SELECT MAX(REFRESHED_AT) FROM MECL_PLATFORM.ANALYTICS.SC_EMS_PART) AS REFRESHED_AT_SC_EMS_PART,
  (SELECT MAX(REFRESHED_AT) FROM MECL_PLATFORM.ANALYTICS.COMPONENT_WHERE_USED) AS REFRESHED_AT_COMPONENT_WHERE_USED
