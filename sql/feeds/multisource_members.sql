-- Multisource_Members: one row per cluster x component, all member statuses.
SELECT
  MS_PART_NUMBER || '|' || PART_NUMBER AS ROW_KEY,
  MS_PART_NUMBER AS ME_MS,
  PART_NUMBER AS ME_EC,
  MEMBER_STATUS AS MEMBER_STATUS,
  IS_USABLE AS IS_USABLE,
  MEMBER_PRIORITY AS MEMBER_PRIORITY,
  MANUFACTURER_NAME AS MANUFACTURER,
  MPN AS MPN
FROM MECL_PLATFORM.ANALYTICS.MULTISOURCE_PART_MEMBERS
