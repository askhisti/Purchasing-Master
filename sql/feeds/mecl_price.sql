-- MECL_Price: one row per quote x linked component (key = price id + part number).
WITH CAT AS (
  SELECT UPPER(TRIM(MANUFACTURER_PARTNUMBER)) AS MPN_KEY, MIN(SUPPLIER_PARTNUMBER) AS ME_EC, COUNT(*) AS N
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_CATALOG
  WHERE NULLIF(TRIM(MANUFACTURER_PARTNUMBER), '') IS NOT NULL
  GROUP BY UPPER(TRIM(MANUFACTURER_PARTNUMBER))
)
SELECT
  I.COMPONENT_PRICE_ID || '|' || COALESCE(I.PART_NUMBER, '') AS ROW_KEY,
  I.COMPONENT_PRICE_ID AS PRICE_ID,
  I.PART_NUMBER AS ME_EC,
  CASE WHEN I.IS_LINKED THEN I.PART_NUMBER WHEN CAT.N = 1 THEN CAT.ME_EC END AS RESOLVED_ME_EC,
  I.IS_LINKED AS IS_LINKED,
  I.PRICE_TYPE AS PRICE_TYPE,
  I.PRICE_OWNER_NAME AS PRICE_OWNER,
  I.VENDOR AS VENDOR,
  I.VENDOR_PARTNUMBER AS VENDOR_PART_NUMBER,
  I.VOLUME_STAGE AS VOLUME_STAGE,
  I.PRICE_YEAR AS PRICE_YEAR,
  I.MINIMUM_ORDER_QUANTITY::FLOAT AS MOQ,
  I.PRICE_PER_UNIT::FLOAT AS PRICE,
  I.CURRENCY AS CURRENCY,
  I.PRICE_PER_UNIT_EUR_AT_CURRENT_RATE::FLOAT AS PRICE_EUR,
  I.QUOTED_UNIT_NORMALIZED AS QUOTED_UNIT,
  I.QUOTED_MANUFACTURER AS QUOTED_MANUFACTURER,
  I.QUOTED_MANUFACTURER_PARTNUMBER AS QUOTED_MPN,
  I.QUOTE_REFERENCE AS QUOTE_REFERENCE,
  I.QUOTE_FILE AS QUOTE_FILE,
  TO_CHAR(I.QUOTE_VALID_START, 'YYYY-MM-DD') AS VALID_FROM,
  TO_CHAR(I.QUOTE_VALID_END, 'YYYY-MM-DD') AS VALID_UNTIL,
  I.IS_VALID_TODAY AS IS_VALID_TODAY,
  I.IS_BINDING AS IS_BINDING,
  TO_CHAR(I.CREATED_AT, 'YYYY-MM-DD HH24:MI:SS') AS CREATED_AT
FROM MECL_PLATFORM.ANALYTICS.COMPONENT_PRICE_ITEMS I
LEFT JOIN CAT ON CAT.MPN_KEY = UPPER(TRIM(I.QUOTED_MANUFACTURER_PARTNUMBER))
