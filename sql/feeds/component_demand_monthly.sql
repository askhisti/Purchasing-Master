-- Component_Demand_Monthly: monthly demand per sourced component, summed over products and flows. Month and year columns come from the SERIES template.
-- F sums each component's demand per month (M = 'YYYY-MM') and rounds that sum to 2 decimals (Q), so each month line stays short.
WITH F AS (
  SELECT
    PART_ID,
    TO_CHAR(MONTH_START, 'YYYY-MM') AS M,
    SUM(DEMAND_QUANTITY) AS RAW_Q,
    SUM(DEMAND_QUANTITY)::NUMBER(38,2) AS Q
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_DEMAND_FORECAST
  WHERE IS_SOURCED_BY_US AND PART_KIND = 'COMPONENT'
  GROUP BY PART_ID, TO_CHAR(MONTH_START, 'YYYY-MM')
),
MS AS (
  SELECT
    COMPONENT_ID,
    MAX(MS_PART_NUMBER) AS PRIMARY_ME_MS
  FROM MECL_PLATFORM.ANALYTICS.MULTISOURCE_PART_MEMBERS
  WHERE IS_USABLE
  GROUP BY COMPONENT_ID
),
L AS (
  SELECT
    F.PART_ID,
    F.M,
    F.RAW_Q,
    F.Q,
    C.SUPPLIER_PARTNUMBER AS ME_EC,
    C.MANUFACTURER_PARTNUMBER AS MPN,
    C.MANUFACTURER_NAME AS MANUFACTURER,
    C.HW_CATEGORY AS HW_CATEGORY,
    C.HW_SUBCATEGORY AS HW_SUBCATEGORY,
    MS.PRIMARY_ME_MS AS PRIMARY_ME_MS
  FROM F
  JOIN MECL_PLATFORM.ANALYTICS.COMPONENT_CATALOG C ON C.COMPONENT_ID = F.PART_ID
  LEFT JOIN MS ON MS.COMPONENT_ID = C.COMPONENT_ID
)
SELECT
  ME_EC AS ROW_KEY,
  ME_EC AS ME_EC,
  MAX(MPN) AS MPN,
  MAX(MANUFACTURER) AS MANUFACTURER,
  MAX(HW_CATEGORY) AS HW_CATEGORY,
  MAX(HW_SUBCATEGORY) AS HW_SUBCATEGORY,
  MAX(PRIMARY_ME_MS) AS PRIMARY_ME_MS
  {{SERIES: ,SUM(IFF(LEFT(M,4)='#YEAR#',Q,0)) AS DEMAND_#YEAR# || ,SUM(IFF(M='#YEAR#-#MM#',Q,0)) AS M_#YEAR#_#MM#}}
FROM L
GROUP BY PART_ID, ME_EC
HAVING SUM(RAW_Q) <> 0
