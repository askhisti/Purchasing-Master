-- Component_Demand_Monthly: monthly demand per sourced component, summed over products and flows. Month columns come from the MONTHS template.
WITH D AS (
  SELECT
    PART_ID,
    SUM(DEMAND_QUANTITY) AS TOTAL_DEMAND
    {{MONTHS: , SUM(IFF(MONTH_START = DATE_FROM_PARTS(#YEAR#, #MONTH#, 1), DEMAND_QUANTITY, 0)) AS M_#YEAR#_#MM#}}
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_DEMAND_FORECAST
  WHERE IS_SOURCED_BY_US AND PART_KIND = 'COMPONENT'
  GROUP BY PART_ID
),
MS AS (
  SELECT
    COMPONENT_ID,
    MAX(MS_PART_NUMBER) AS PRIMARY_ME_MS
  FROM MECL_PLATFORM.ANALYTICS.MULTISOURCE_PART_MEMBERS
  WHERE IS_USABLE
  GROUP BY COMPONENT_ID
)
SELECT
  C.SUPPLIER_PARTNUMBER AS ROW_KEY,
  C.SUPPLIER_PARTNUMBER AS ME_EC,
  C.MANUFACTURER_PARTNUMBER AS MPN,
  C.MANUFACTURER_NAME AS MANUFACTURER,
  C.HW_CATEGORY AS HW_CATEGORY,
  C.HW_SUBCATEGORY AS HW_SUBCATEGORY,
  MS.PRIMARY_ME_MS AS PRIMARY_ME_MS
  {{MONTHS: , D.M_#YEAR#_#MM# AS M_#YEAR#_#MM#}}
FROM D
JOIN MECL_PLATFORM.ANALYTICS.COMPONENT_CATALOG C ON C.COMPONENT_ID = D.PART_ID
LEFT JOIN MS ON MS.COMPONENT_ID = C.COMPONENT_ID
WHERE D.TOTAL_DEMAND <> 0
