-- Multisource_Health: one row per COMPONENT_SOURCING component. Only SINGLE_SOURCE is a true single source.
WITH MS AS (
  SELECT COMPONENT_ID, MAX(MS_PART_NUMBER) AS PRIMARY_ME_MS
  FROM MECL_PLATFORM.ANALYTICS.MULTISOURCE_PART_MEMBERS
  WHERE IS_USABLE
  GROUP BY COMPONENT_ID
),
D AS (
  SELECT PART_ID, SUM(TOTAL_DEMAND) AS DEMAND_CUR
  FROM MECL_PLATFORM.ANALYTICS.KPI_COMPONENT_DEMAND_BY_YEAR
  WHERE PART_KIND = 'COMPONENT' AND IS_SOURCED_BY_US
    AND DEMAND_YEAR = YEAR(CONVERT_TIMEZONE('Europe/Berlin', CURRENT_TIMESTAMP()))
  GROUP BY PART_ID
),
MP AS (
  SELECT MS_PART_NUMBER, MAX(SOURCING_HEALTH) AS SOURCING_HEALTH
  FROM MECL_PLATFORM.ANALYTICS.MULTISOURCE_PARTS
  GROUP BY MS_PART_NUMBER
)
SELECT
  S.PART_NUMBER AS ROW_KEY,
  S.PART_NUMBER AS ME_EC,
  S.MPN AS MPN,
  S.MANUFACTURER_NAME AS MANUFACTURER,
  S.HW_CATEGORY AS HW_CATEGORY,
  S.SOURCING_LEVEL AS SOURCING_LEVEL,
  S.TRUE_SINGLE_SOURCE_PLACEMENTS AS TRUE_SINGLE_SOURCE_PLACEMENTS,
  S.SINGLE_SOURCE_REASONS AS SINGLE_SOURCE_REASONS,
  S.USABLE_ALTERNATES AS USABLE_ALTERNATES,
  S.MULTISOURCE_PARTS AS ME_MS,
  MP.SOURCING_HEALTH AS CLUSTER_SOURCING_HEALTH,
  S.PRODUCTS_USING AS PRODUCTS_USING,
  COALESCE(D.DEMAND_CUR, 0) AS DEMAND_CURRENT_YEAR
FROM MECL_PLATFORM.ANALYTICS.COMPONENT_SOURCING S
LEFT JOIN MS ON MS.COMPONENT_ID = S.COMPONENT_ID
LEFT JOIN MP ON MP.MS_PART_NUMBER = MS.PRIMARY_ME_MS
LEFT JOIN D ON D.PART_ID = S.COMPONENT_ID
