-- BOM_Demand_Monthly: monthly demand per sourced component x product x flow, with quantity per unit. Month and year columns come from the SERIES template.
-- F sums the demand per line and month (M = 'YYYY-MM') and rounds that sum to 2 decimals (Q), so each month line stays short.
WITH F AS (
  SELECT
    PART_ID,
    PRODUCT_ID,
    INITCAP(PRODUCT_FLOW_TYPE) AS FLOW,
    TO_CHAR(MONTH_START, 'YYYY-MM') AS M,
    MAX(PRODUCT_DISPLAY_NAME) AS PRODUCT_DISPLAY_NAME,
    MAX(EMS_NAME) AS EMS_NAME,
    MAX(QTY_PER_UNIT) AS QTY_PER_UNIT,
    SUM(DEMAND_QUANTITY)::NUMBER(38,2) AS Q
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_DEMAND_FORECAST
  WHERE IS_SOURCED_BY_US AND PART_KIND = 'COMPONENT'
  GROUP BY PART_ID, PRODUCT_ID, INITCAP(PRODUCT_FLOW_TYPE), TO_CHAR(MONTH_START, 'YYYY-MM')
),
L AS (
  SELECT
    F.*,
    C.SUPPLIER_PARTNUMBER AS ME_EC,
    C.MANUFACTURER_PARTNUMBER AS MPN,
    C.MANUFACTURER_NAME AS MANUFACTURER
  FROM F
  JOIN MECL_PLATFORM.ANALYTICS.COMPONENT_CATALOG C ON C.COMPONENT_ID = F.PART_ID
)
SELECT
  ME_EC || '|' || PRODUCT_ID::VARCHAR || '|' || FLOW AS ROW_KEY,
  ME_EC AS ME_EC,
  MAX(MPN) AS MPN,
  MAX(MANUFACTURER) AS MANUFACTURER,
  MAX(PRODUCT_DISPLAY_NAME) AS PRODUCT,
  PRODUCT_ID AS PRODUCT_ID,
  MAX(EMS_NAME) AS EMS,
  FLOW AS FLOW,
  MAX(QTY_PER_UNIT)::FLOAT AS QTY_PER_UNIT
  {{SERIES: ,SUM(IFF(LEFT(M,4)='#YEAR#',Q,0)) AS DEMAND_#YEAR# || ,SUM(IFF(M='#YEAR#-#MM#',Q,0)) AS M_#YEAR#_#MM#}}
FROM L
GROUP BY PART_ID, ME_EC, PRODUCT_ID, FLOW
