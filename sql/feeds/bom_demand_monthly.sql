-- BOM_Demand_Monthly: monthly demand per sourced component x product x flow, with quantity per unit. Month columns come from the MONTHS template.
-- F sums the demand per line and month (M = 'YYYY-MM') and rounds that sum to 2 decimals (Q), so each month line stays short.
WITH F AS (
  SELECT
    PART_ID,
    PRODUCT_ID,
    INITCAP(PRODUCT_FLOW_TYPE) AS FLOW,
    TO_CHAR(MONTH_START, 'YYYY-MM') AS M,
    MAX(PRODUCT_DISPLAY_NAME) AS PRODUCT_DISPLAY_NAME,
    MAX(EMS_NAME) AS EMS_NAME,
    MAX(QTY_PER_UNIT) AS QTY_PER_UNIT,
    SUM(DEMAND_QUANTITY)::NUMBER(38,2) AS Q
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_DEMAND_FORECAST
  WHERE IS_SOURCED_BY_US AND PART_KIND = 'COMPONENT'
  GROUP BY PART_ID, PRODUCT_ID, INITCAP(PRODUCT_FLOW_TYPE), TO_CHAR(MONTH_START, 'YYYY-MM')
),
B AS (
  SELECT
    PART_ID,
    PRODUCT_ID,
    FLOW,
    MAX(PRODUCT_DISPLAY_NAME) AS PRODUCT_DISPLAY_NAME,
    MAX(EMS_NAME) AS EMS_NAME,
    MAX(QTY_PER_UNIT) AS QTY_PER_UNIT
    {{MONTHS: ,SUM(IFF(M='#YEAR#-#MM#',Q,0)) AS M_#YEAR#_#MM#}}
  FROM F
  GROUP BY PART_ID, PRODUCT_ID, FLOW
)
SELECT
  C.SUPPLIER_PARTNUMBER || '|' || B.PRODUCT_ID::VARCHAR || '|' || B.FLOW AS ROW_KEY,
  C.SUPPLIER_PARTNUMBER AS ME_EC,
  C.MANUFACTURER_PARTNUMBER AS MPN,
  C.MANUFACTURER_NAME AS MANUFACTURER,
  B.PRODUCT_DISPLAY_NAME AS PRODUCT,
  B.PRODUCT_ID AS PRODUCT_ID,
  B.EMS_NAME AS EMS,
  B.FLOW AS FLOW,
  B.QTY_PER_UNIT::FLOAT AS QTY_PER_UNIT,
  B.* EXCLUDE (PART_ID, PRODUCT_ID, FLOW, PRODUCT_DISPLAY_NAME, EMS_NAME, QTY_PER_UNIT)
FROM B
JOIN MECL_PLATFORM.ANALYTICS.COMPONENT_CATALOG C ON C.COMPONENT_ID = B.PART_ID
