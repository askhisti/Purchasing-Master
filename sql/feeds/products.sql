-- Products: one row per customer product.
SELECT
  PRODUCT_ID::VARCHAR AS ROW_KEY,
  PRODUCT_ID AS PRODUCT_ID,
  PRODUCT_DISPLAY_NAME AS PRODUCT_DISPLAY_NAME,
  PROJECT_NAME AS PROJECT,
  PROGRAM_NAME AS PROGRAM,
  CUSTOMER_NAME AS CUSTOMER,
  PRODUCT_SAMPLE_PHASE AS SAMPLE_PHASE,
  EMS_NAME AS EMS,
  TO_CHAR(START_OF_PRODUCTION, 'YYYY-MM-DD') AS SOP,
  IS_HIERARCHY_ACTIVE AS IS_HIERARCHY_ACTIVE
FROM MECL_PLATFORM.ANALYTICS.PRODUCT_CATALOG
