-- Multisource: one row per cluster; demand = sum over that cluster's own usable members only. Placeholder: {{BASE_YEAR}}.
WITH MEMBER_DEMAND AS (
  SELECT
    M.MULTISOURCE_ID,
    SUM(IFF(K.IS_SOURCED_BY_US AND K.DEMAND_YEAR = {{BASE_YEAR}} + 0, K.TOTAL_DEMAND, 0)) AS DEMAND_Y0,
    SUM(IFF(K.IS_SOURCED_BY_US AND K.DEMAND_YEAR = {{BASE_YEAR}} + 1, K.TOTAL_DEMAND, 0)) AS DEMAND_Y1,
    SUM(IFF(K.IS_SOURCED_BY_US AND K.DEMAND_YEAR = {{BASE_YEAR}} + 2, K.TOTAL_DEMAND, 0)) AS DEMAND_Y2,
    SUM(IFF(K.IS_SOURCED_BY_US AND K.DEMAND_YEAR = {{BASE_YEAR}} + 3, K.TOTAL_DEMAND, 0)) AS DEMAND_Y3,
    SUM(IFF(K.IS_SOURCED_BY_US AND K.DEMAND_YEAR = {{BASE_YEAR}} + 4, K.TOTAL_DEMAND, 0)) AS DEMAND_Y4,
    SUM(IFF(K.IS_SOURCED_BY_US AND K.DEMAND_YEAR = {{BASE_YEAR}} + 5, K.TOTAL_DEMAND, 0)) AS DEMAND_Y5,
    SUM(IFF(K.IS_SOURCED_BY_US AND K.DEMAND_YEAR = {{BASE_YEAR}} + 6, K.TOTAL_DEMAND, 0)) AS DEMAND_Y6,
    SUM(IFF(K.IS_SOURCED_BY_US AND K.DEMAND_YEAR = {{BASE_YEAR}} + 7, K.TOTAL_DEMAND, 0)) AS DEMAND_Y7,
    SUM(IFF(K.IS_SOURCED_BY_US AND K.DEMAND_YEAR = {{BASE_YEAR}} + 8, K.TOTAL_DEMAND, 0)) AS DEMAND_Y8,
    SUM(IFF(K.IS_SOURCED_BY_US AND K.DEMAND_YEAR = {{BASE_YEAR}} + 9, K.TOTAL_DEMAND, 0)) AS DEMAND_Y9,
    SUM(IFF(K.IS_SOURCED_BY_US AND K.DEMAND_YEAR = {{BASE_YEAR}} + 10, K.TOTAL_DEMAND, 0)) AS DEMAND_Y10
  FROM MECL_PLATFORM.ANALYTICS.MULTISOURCE_PART_MEMBERS M
  JOIN MECL_PLATFORM.ANALYTICS.KPI_COMPONENT_DEMAND_BY_YEAR K
    ON K.PART_ID = M.COMPONENT_ID AND K.PART_KIND = 'COMPONENT'
  WHERE M.IS_USABLE
  GROUP BY M.MULTISOURCE_ID
)
SELECT
  P.MS_PART_NUMBER AS ROW_KEY,
  P.MS_PART_NUMBER AS ME_MS,
  P.SOURCING_HEALTH AS SOURCING_HEALTH,
  P.MEMBER_COUNT AS MEMBER_COUNT,
  P.USABLE_MEMBERS AS USABLE_MEMBER_COUNT,
  P.MANUFACTURER_COUNT AS MANUFACTURER_COUNT,
  COALESCE(D.DEMAND_Y0, 0) AS DEMAND_Y0,
  COALESCE(D.DEMAND_Y1, 0) AS DEMAND_Y1,
  COALESCE(D.DEMAND_Y2, 0) AS DEMAND_Y2,
  COALESCE(D.DEMAND_Y3, 0) AS DEMAND_Y3,
  COALESCE(D.DEMAND_Y4, 0) AS DEMAND_Y4,
  COALESCE(D.DEMAND_Y5, 0) AS DEMAND_Y5,
  COALESCE(D.DEMAND_Y6, 0) AS DEMAND_Y6,
  COALESCE(D.DEMAND_Y7, 0) AS DEMAND_Y7,
  COALESCE(D.DEMAND_Y8, 0) AS DEMAND_Y8,
  COALESCE(D.DEMAND_Y9, 0) AS DEMAND_Y9,
  COALESCE(D.DEMAND_Y10, 0) AS DEMAND_Y10
FROM MECL_PLATFORM.ANALYTICS.MULTISOURCE_PARTS P
LEFT JOIN MEMBER_DEMAND D ON D.MULTISOURCE_ID = P.MULTISOURCE_ID
