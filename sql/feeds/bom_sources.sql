-- BOM_Sources: one row per BOM line (product x sourced primary component) and source. Position 1 is the primary itself; further positions are usable alternatives from the multisource clusters the primary belongs to. Volumes are the line's demand over both flows, rounded to 2 decimals after summing.
WITH L AS (
  SELECT
    PRODUCT_ID,
    PART_ID,
    MAX(PRODUCT_DISPLAY_NAME) AS PRODUCT_DISPLAY_NAME,
    MAX(EMS_NAME) AS EMS_NAME
    {{DEMAND: , SUM(IFF(DEMAND_YEAR = #YEAR#, DEMAND_QUANTITY, 0))::NUMBER(38,2) AS V_#YEAR#}}
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_DEMAND_FORECAST
  WHERE IS_SOURCED_BY_US AND PART_KIND = 'COMPONENT'
  GROUP BY PRODUCT_ID, PART_ID
),
A0 AS (
  SELECT
    L.PRODUCT_ID,
    L.PART_ID,
    M2.COMPONENT_ID AS SRC_ID,
    M2.MS_PART_NUMBER,
    M2.MEMBER_PRIORITY,
    M2.MEMBER_STATUS,
    M2.IS_USABLE
  FROM L
  JOIN MECL_PLATFORM.ANALYTICS.MULTISOURCE_PART_MEMBERS M1 ON M1.COMPONENT_ID = L.PART_ID
  JOIN MECL_PLATFORM.ANALYTICS.MULTISOURCE_PART_MEMBERS M2
    ON M2.MULTISOURCE_ID = M1.MULTISOURCE_ID AND M2.IS_USABLE AND M2.COMPONENT_ID <> L.PART_ID
  QUALIFY ROW_NUMBER() OVER (PARTITION BY L.PRODUCT_ID, L.PART_ID, M2.COMPONENT_ID ORDER BY M2.MEMBER_PRIORITY, M2.MS_PART_NUMBER) = 1
),
A1 AS (
  SELECT
    A0.PRODUCT_ID,
    A0.PART_ID,
    A0.SRC_ID,
    A0.MS_PART_NUMBER,
    A0.MEMBER_STATUS,
    A0.IS_USABLE,
    1 + ROW_NUMBER() OVER (PARTITION BY A0.PRODUCT_ID, A0.PART_ID ORDER BY A0.MEMBER_PRIORITY, CA.SUPPLIER_PARTNUMBER, A0.SRC_ID) AS SOURCE_POSITION
  FROM A0
  JOIN MECL_PLATFORM.ANALYTICS.COMPONENT_CATALOG CA ON CA.COMPONENT_ID = A0.SRC_ID
),
S AS (
  SELECT PRODUCT_ID, PART_ID, PART_ID AS SRC_ID, 1 AS SOURCE_POSITION, NULL::VARCHAR AS MS_PART_NUMBER, NULL::VARCHAR AS MEMBER_STATUS, NULL::BOOLEAN AS IS_USABLE, 'Demand' AS VOLUME_TYPE
  FROM L
  UNION ALL
  SELECT PRODUCT_ID, PART_ID, SRC_ID, SOURCE_POSITION, MS_PART_NUMBER, MEMBER_STATUS, IS_USABLE, 'Potential volume if sourced'
  FROM A1
)
SELECT
  S.PRODUCT_ID::VARCHAR || '|' || CB.SUPPLIER_PARTNUMBER || '|' || LPAD(S.SOURCE_POSITION::VARCHAR, 3, '0') AS ROW_KEY,
  L.PRODUCT_DISPLAY_NAME AS PRODUCT,
  S.PRODUCT_ID AS PRODUCT_ID,
  L.EMS_NAME AS EMS,
  CB.SUPPLIER_PARTNUMBER AS BOM_ME_EC,
  S.MS_PART_NUMBER AS ME_MS,
  S.SOURCE_POSITION AS SOURCE_POSITION,
  CS.SUPPLIER_PARTNUMBER AS SOURCE_ME_EC,
  CS.MANUFACTURER_NAME AS MANUFACTURER,
  CS.MANUFACTURER_PARTNUMBER AS MPN,
  CS.HW_CATEGORY AS HW_CATEGORY,
  CS.HW_SUBCATEGORY AS HW_SUBCATEGORY,
  S.MEMBER_STATUS AS MEMBER_STATUS,
  S.IS_USABLE AS IS_USABLE,
  S.VOLUME_TYPE AS VOLUME_TYPE
  {{DEMAND: , L.V_#YEAR# AS VOLUME_#YEAR#}}
FROM S
JOIN L ON L.PRODUCT_ID = S.PRODUCT_ID AND L.PART_ID = S.PART_ID
JOIN MECL_PLATFORM.ANALYTICS.COMPONENT_CATALOG CB ON CB.COMPONENT_ID = S.PART_ID
JOIN MECL_PLATFORM.ANALYTICS.COMPONENT_CATALOG CS ON CS.COMPONENT_ID = S.SRC_ID
