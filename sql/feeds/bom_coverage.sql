-- BOM_Coverage: one row per plan year; released share is weighted by planned units.
SELECT
  TO_VARCHAR(PLAN_YEAR) AS ROW_KEY,
  PLAN_YEAR AS YEAR,
  SUM(PLANNED_UNITS) AS PLANNED_UNITS,
  SUM(IFF(DEMAND_BASIS = 'RELEASED_BOM', PLANNED_UNITS, 0)) AS RELEASED_BOM_UNITS,
  ROUND(100 * SUM(IFF(DEMAND_BASIS = 'RELEASED_BOM', PLANNED_UNITS, 0)) / NULLIF(SUM(PLANNED_UNITS), 0), 1) AS RELEASED_BOM_SHARE_PCT
FROM MECL_PLATFORM.ANALYTICS.PRODUCT_DEMAND_BASIS
GROUP BY PLAN_YEAR
