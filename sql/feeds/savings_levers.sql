-- Savings_Levers: one row per component x demand year x EMS; never add lever columns together; LOA pass-through is a risk, not a saving.
SELECT
  PART_NUMBER || '|' || DEMAND_YEAR || '|' || COALESCE(TO_VARCHAR(EMS_ID), '-') AS ROW_KEY,
  PART_NUMBER AS ME_EC,
  MPN AS MPN,
  MANUFACTURER_NAME AS MANUFACTURER,
  DEMAND_YEAR AS DEMAND_YEAR,
  EMS_NAME AS EMS,
  SPEND_RANK_IN_YEAR AS SPEND_RANK_IN_YEAR,
  CUMULATIVE_SPEND_SHARE_PCT AS CUMULATIVE_SPEND_SHARE_PCT,
  EXPECTED_SPEND_EUR AS EXPECTED_SPEND_EUR,
  COMPONENT_SPEND_IN_YEAR_EUR AS COMPONENT_SPEND_IN_YEAR_EUR,
  LOA_PASS_THROUGH_VALUE_EUR AS LOA_PASS_THROUGH_RISK_EUR,
  NO_LOA_SPEND_EUR AS NO_LOA_SPEND_EUR,
  EMS_HARMONISATION_SAVING_EUR AS EMS_HARMONISATION_SAVING_EUR,
  LOWEST_EMS_NAME AS LOWEST_EMS,
  LOWEST_EMS_PRICE_EUR AS LOWEST_EMS_PRICE_EUR,
  ALTERNATIVE_SAVING_EUR AS ALTERNATIVE_SAVING_EUR,
  BEST_ALTERNATIVE_MPN AS BEST_ALTERNATIVE_MPN,
  BEST_ALTERNATIVE_PRICE_EUR AS BEST_ALTERNATIVE_PRICE_EUR,
  STALE_PRICE_SPEND_EUR AS STALE_PRICE_SPEND_EUR,
  BELOW_LOWEST_STAGE_SPEND_EUR AS BELOW_LOWEST_STAGE_SPEND_EUR,
  GAP_TO_TARGET_EUR AS GAP_TO_TARGET_EUR,
  IS_QUOTE_EXPIRED AS IS_QUOTE_EXPIRED,
  IS_CARRIED_FORWARD AS IS_CARRIED_FORWARD,
  TO_CHAR(PRICE_VALID_UNTIL, 'YYYY-MM-DD') AS PRICE_VALID_UNTIL,
  HAS_LOA_PRICE AS HAS_LOA_PRICE,
  HAS_TARGET_PRICE AS HAS_TARGET_PRICE,
  TO_VARCHAR(CONVERT_TIMEZONE('Europe/Berlin', REFRESHED_AT), 'YYYY-MM-DD HH24:MI') AS SOURCE_REFRESHED_AT
FROM MECL_PLATFORM.ANALYTICS.COMPONENT_SAVINGS_LEVERS
