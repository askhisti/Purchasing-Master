-- Quote_Health: one row per ME_EC with at least one LOA/EMS quote or any sourced demand.
-- Quotes are attributed to the Resolved ME_EC exactly as in MECL_Price (linked part number, else the single catalog component with the same MPN).
WITH T AS (
  SELECT
    CONVERT_TIMEZONE('Europe/Berlin', CURRENT_TIMESTAMP())::DATE AS TODAY,
    YEAR(CONVERT_TIMEZONE('Europe/Berlin', CURRENT_TIMESTAMP())) AS CUR_YEAR
),
CAT AS (
  SELECT UPPER(TRIM(MANUFACTURER_PARTNUMBER)) AS MPN_KEY, MIN(SUPPLIER_PARTNUMBER) AS ME_EC, COUNT(*) AS N
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_CATALOG
  WHERE NULLIF(TRIM(MANUFACTURER_PARTNUMBER), '') IS NOT NULL
  GROUP BY UPPER(TRIM(MANUFACTURER_PARTNUMBER))
),
QI AS (
  SELECT
    CASE WHEN I.IS_LINKED THEN I.PART_NUMBER WHEN CAT.N = 1 THEN CAT.ME_EC END AS RESOLVED_ME_EC,
    I.PRICE_TYPE,
    COALESCE(I.IS_VALID_TODAY, FALSE) AS IS_VALID,
    I.QUOTE_VALID_END::DATE AS VALID_END,
    I.CREATED_AT
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_PRICE_ITEMS I
  LEFT JOIN CAT ON CAT.MPN_KEY = UPPER(TRIM(I.QUOTED_MANUFACTURER_PARTNUMBER))
  WHERE I.PRICE_TYPE IN ('LOA', 'EMS')
),
Q AS (
  SELECT
    QI.RESOLVED_ME_EC AS ME_EC,
    COUNT_IF(QI.PRICE_TYPE = 'LOA' AND QI.IS_VALID) AS VALID_LOA,
    COUNT_IF(QI.PRICE_TYPE = 'LOA' AND QI.VALID_END < T.TODAY) AS EXPIRED_LOA,
    COUNT_IF(QI.PRICE_TYPE = 'LOA' AND QI.IS_VALID AND QI.VALID_END IS NULL) AS OPEN_LOA,
    MAX(IFF(QI.PRICE_TYPE = 'LOA' AND QI.IS_VALID, QI.VALID_END, NULL)) AS LOA_MAX_END,
    COUNT_IF(QI.PRICE_TYPE = 'EMS' AND QI.IS_VALID) AS VALID_EMS,
    COUNT_IF(QI.PRICE_TYPE = 'EMS' AND QI.VALID_END < T.TODAY) AS EXPIRED_EMS,
    COUNT_IF(QI.PRICE_TYPE = 'EMS' AND QI.IS_VALID AND QI.VALID_END IS NULL) AS OPEN_EMS,
    MAX(IFF(QI.PRICE_TYPE = 'EMS' AND QI.IS_VALID, QI.VALID_END, NULL)) AS EMS_MAX_END,
    MAX(QI.CREATED_AT)::DATE AS LAST_QUOTED
  FROM QI CROSS JOIN T
  WHERE QI.RESOLVED_ME_EC IS NOT NULL
  GROUP BY QI.RESOLVED_ME_EC
),
DY AS (
  SELECT PART_ID, DEMAND_YEAR, SUM(DEMAND_QUANTITY) AS QTY
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_DEMAND_FORECAST
  WHERE IS_SOURCED_BY_US AND PART_KIND = 'COMPONENT'
  GROUP BY PART_ID, DEMAND_YEAR
),
D AS (
  SELECT DY.PART_ID, MIN(IFF(DY.QTY > 0 AND DY.DEMAND_YEAR >= T.CUR_YEAR, DY.DEMAND_YEAR, NULL)) AS NEXT_YEAR
  FROM DY CROSS JOIN T
  GROUP BY DY.PART_ID
),
D12 AS (
  SELECT F.PART_ID, SUM(F.DEMAND_QUANTITY) AS DEMAND_12M
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_DEMAND_FORECAST F CROSS JOIN T
  WHERE F.IS_SOURCED_BY_US AND F.PART_KIND = 'COMPONENT'
    AND F.MONTH_START >= DATE_TRUNC('MONTH', T.TODAY)
    AND F.MONTH_START < DATEADD('MONTH', 12, DATE_TRUNC('MONTH', T.TODAY))
  GROUP BY F.PART_ID
),
SL AS (
  SELECT L.PART_NUMBER, SUM(L.STALE_PRICE_SPEND_EUR) AS STALE_EUR
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_SAVINGS_LEVERS L CROSS JOIN T
  WHERE L.DEMAND_YEAR = T.CUR_YEAR
  GROUP BY L.PART_NUMBER
)
SELECT
  C.SUPPLIER_PARTNUMBER AS ROW_KEY,
  C.SUPPLIER_PARTNUMBER AS ME_EC,
  C.MANUFACTURER_PARTNUMBER AS MPN,
  C.MANUFACTURER_NAME AS MANUFACTURER,
  C.HW_CATEGORY AS HW_CATEGORY,
  D.NEXT_YEAR AS NEXT_DEMAND_YEAR,
  COALESCE(D12.DEMAND_12M, 0) AS DEMAND_NEXT_12_MONTHS,
  COALESCE(Q.VALID_LOA, 0) AS VALID_LOA_QUOTES,
  COALESCE(Q.EXPIRED_LOA, 0) AS EXPIRED_LOA_QUOTES,
  IFF(COALESCE(Q.OPEN_LOA, 0) > 0, NULL, TO_CHAR(Q.LOA_MAX_END, 'YYYY-MM-DD')) AS LOA_VALID_UNTIL,
  COALESCE(Q.VALID_EMS, 0) AS VALID_EMS_QUOTES,
  COALESCE(Q.EXPIRED_EMS, 0) AS EXPIRED_EMS_QUOTES,
  IFF(COALESCE(Q.OPEN_EMS, 0) > 0, NULL, TO_CHAR(Q.EMS_MAX_END, 'YYYY-MM-DD')) AS EMS_VALID_UNTIL,
  TO_CHAR(Q.LAST_QUOTED, 'YYYY-MM-DD') AS LAST_QUOTED_ON,
  COALESCE(SL.STALE_EUR, 0) AS STALE_PRICE_SPEND_EUR,
  CASE
    WHEN Q.ME_EC IS NULL THEN 'No quote'
    WHEN Q.VALID_LOA + Q.VALID_EMS = 0 THEN 'All expired'
    WHEN Q.OPEN_LOA + Q.OPEN_EMS = 0 AND GREATEST(COALESCE(Q.LOA_MAX_END, DATE '1900-01-01'), COALESCE(Q.EMS_MAX_END, DATE '1900-01-01')) <= DATEADD('DAY', 90, T.TODAY) THEN 'Expires within 90 days'
    ELSE 'Valid'
  END AS STATUS
FROM MECL_PLATFORM.ANALYTICS.COMPONENT_CATALOG C
CROSS JOIN T
LEFT JOIN Q ON Q.ME_EC = C.SUPPLIER_PARTNUMBER
LEFT JOIN D ON D.PART_ID = C.COMPONENT_ID
LEFT JOIN D12 ON D12.PART_ID = C.COMPONENT_ID
LEFT JOIN SL ON SL.PART_NUMBER = C.SUPPLIER_PARTNUMBER
WHERE Q.ME_EC IS NOT NULL OR D.PART_ID IS NOT NULL
