-- Price_At_Demand: one row per component x demand year x EMS; EUR at today's rate, estimate based on quotes, not paid prices.
SELECT
  PART_NUMBER || '|' || DEMAND_YEAR || '|' || COALESCE(TO_VARCHAR(EMS_ID), '-') AS ROW_KEY,
  PART_NUMBER AS ME_EC,
  MPN AS MPN,
  MANUFACTURER_NAME AS MANUFACTURER,
  DEMAND_YEAR AS YEAR,
  EMS_NAME AS EMS,
  EMS_DEMAND AS EMS_DEMAND,
  TOTAL_DEMAND AS TOTAL_DEMAND,
  EMS_PRICE_EUR AS EMS_PRICE_EUR,
  EMS_PRICE_STAGE AS EMS_PRICE_STAGE,
  LOA_PRICE_EUR AS LOA_PRICE_EUR,
  LOA_PRICE_STAGE AS LOA_PRICE_STAGE,
  TARGET_PRICE_EUR AS TARGET_PRICE_EUR,
  BEST_BINDING_PRICE_EUR AS BEST_BINDING_PRICE_EUR,
  BEST_BINDING_PRICE_TYPE AS BEST_BINDING_PRICE_TYPE,
  EXPECTED_SPEND_EUR AS EXPECTED_SPEND_EUR,
  TARGET_SPEND_EUR AS TARGET_SPEND_EUR,
  GAP_TO_TARGET_EUR AS GAP_TO_TARGET_EUR,
  IS_PRICED AS IS_PRICED,
  IS_BELOW_LOWEST_STAGE AS IS_BELOW_LOWEST_STAGE,
  TO_VARCHAR(CONVERT_TIMEZONE('Europe/Berlin', REFRESHED_AT), 'YYYY-MM-DD HH24:MI') AS SOURCE_REFRESHED_AT
FROM MECL_PLATFORM.ANALYTICS.COMPONENT_PRICE_AT_DEMAND
