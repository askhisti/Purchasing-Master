-- Components: one row per COMPONENT_CATALOG component (ME_EC / ME_MC). Placeholder: {{BASE_YEAR}}.
WITH DEMAND AS (
  SELECT
    PART_ID,
    BOOLOR_AGG(IS_SOURCED_BY_US) AS ANY_SOURCED,
    SUM(IFF(IS_SOURCED_BY_US AND DEMAND_YEAR = {{BASE_YEAR}} + 0, TOTAL_DEMAND, 0)) AS DEMAND_Y0,
    SUM(IFF(IS_SOURCED_BY_US AND DEMAND_YEAR = {{BASE_YEAR}} + 1, TOTAL_DEMAND, 0)) AS DEMAND_Y1,
    SUM(IFF(IS_SOURCED_BY_US AND DEMAND_YEAR = {{BASE_YEAR}} + 2, TOTAL_DEMAND, 0)) AS DEMAND_Y2,
    SUM(IFF(IS_SOURCED_BY_US AND DEMAND_YEAR = {{BASE_YEAR}} + 3, TOTAL_DEMAND, 0)) AS DEMAND_Y3,
    SUM(IFF(IS_SOURCED_BY_US AND DEMAND_YEAR = {{BASE_YEAR}} + 4, TOTAL_DEMAND, 0)) AS DEMAND_Y4,
    SUM(IFF(IS_SOURCED_BY_US AND DEMAND_YEAR = {{BASE_YEAR}} + 5, TOTAL_DEMAND, 0)) AS DEMAND_Y5,
    SUM(IFF(IS_SOURCED_BY_US AND DEMAND_YEAR = {{BASE_YEAR}} + 6, TOTAL_DEMAND, 0)) AS DEMAND_Y6,
    SUM(IFF(IS_SOURCED_BY_US AND DEMAND_YEAR = {{BASE_YEAR}} + 7, TOTAL_DEMAND, 0)) AS DEMAND_Y7,
    SUM(IFF(IS_SOURCED_BY_US AND DEMAND_YEAR = {{BASE_YEAR}} + 8, TOTAL_DEMAND, 0)) AS DEMAND_Y8,
    SUM(IFF(IS_SOURCED_BY_US AND DEMAND_YEAR = {{BASE_YEAR}} + 9, TOTAL_DEMAND, 0)) AS DEMAND_Y9,
    SUM(IFF(IS_SOURCED_BY_US AND DEMAND_YEAR = {{BASE_YEAR}} + 10, TOTAL_DEMAND, 0)) AS DEMAND_Y10
  FROM MECL_PLATFORM.ANALYTICS.KPI_COMPONENT_DEMAND_BY_YEAR
  WHERE PART_KIND = 'COMPONENT'
  GROUP BY PART_ID
),
MS AS (
  SELECT
    COMPONENT_ID,
    LISTAGG(DISTINCT MS_PART_NUMBER, ', ') WITHIN GROUP (ORDER BY MS_PART_NUMBER) AS ME_MS,
    MAX(MS_PART_NUMBER) AS PRIMARY_ME_MS
  FROM MECL_PLATFORM.ANALYTICS.MULTISOURCE_PART_MEMBERS
  WHERE IS_USABLE
  GROUP BY COMPONENT_ID
),
EMS AS (
  SELECT
    PRIMARY_COMPONENT_ID AS COMPONENT_ID,
    LISTAGG(DISTINCT EMS_CODE || ':' || EMS_PART, ', ') WITHIN GROUP (ORDER BY EMS_CODE || ':' || EMS_PART) AS EMS_PART_NUMBERS
  FROM MECL_PLATFORM.ANALYTICS.SC_EMS_PART
  WHERE IS_IN_LATEST_SNAPSHOT AND PRIMARY_COMPONENT_ID IS NOT NULL
  GROUP BY PRIMARY_COMPONENT_ID
)
SELECT
  C.SUPPLIER_PARTNUMBER AS ROW_KEY,
  C.SUPPLIER_PARTNUMBER AS ME_EC,
  C.MANUFACTURER_NAME AS MANUFACTURER,
  C.MANUFACTURER_PARTNUMBER AS MPN,
  COALESCE(NULLIF(C.CORE_DESCRIPTION, ''), NULLIF(C.HW_DESCRIPTION, '')) AS DESCRIPTION,
  C.HW_CATEGORY AS HW_CATEGORY,
  C.HW_SUBCATEGORY AS HW_SUBCATEGORY,
  C.COMPONENT_STATUS AS COMPONENT_STATUS,
  COALESCE(NULLIF(C.HW_LIFECYCLE, ''), NULLIF(C.SE_LIFECYCLE, '')) AS LIFECYCLE,
  C.YEARS_TO_END_OF_LIFE::FLOAT AS YEARS_TO_EOL,
  MS.ME_MS AS ME_MS,
  MS.PRIMARY_ME_MS AS PRIMARY_ME_MS,
  EMS.EMS_PART_NUMBERS AS EMS_PART_NUMBERS,
  COALESCE(D.ANY_SOURCED, FALSE) AS IS_SOURCED_BY_US,
  COALESCE(D.DEMAND_Y0, 0) AS DEMAND_Y0,
  COALESCE(D.DEMAND_Y1, 0) AS DEMAND_Y1,
  COALESCE(D.DEMAND_Y2, 0) AS DEMAND_Y2,
  COALESCE(D.DEMAND_Y3, 0) AS DEMAND_Y3,
  COALESCE(D.DEMAND_Y4, 0) AS DEMAND_Y4,
  COALESCE(D.DEMAND_Y5, 0) AS DEMAND_Y5,
  COALESCE(D.DEMAND_Y6, 0) AS DEMAND_Y6,
  COALESCE(D.DEMAND_Y7, 0) AS DEMAND_Y7,
  COALESCE(D.DEMAND_Y8, 0) AS DEMAND_Y8,
  COALESCE(D.DEMAND_Y9, 0) AS DEMAND_Y9,
  COALESCE(D.DEMAND_Y10, 0) AS DEMAND_Y10
FROM MECL_PLATFORM.ANALYTICS.COMPONENT_CATALOG C
LEFT JOIN DEMAND D ON D.PART_ID = C.COMPONENT_ID
LEFT JOIN MS ON MS.COMPONENT_ID = C.COMPONENT_ID
LEFT JOIN EMS ON EMS.COMPONENT_ID = C.COMPONENT_ID
