-- Product_Volumes: planned finished units per product x flow. Year and month columns come from the SERIES template.
-- PM has one row per product, flow and month: Y is its year, U its units, M its month ('YYYY-MM') and Q its units rounded to 2 decimals.
-- Year cells are rounded after summing. M and Q are unqualified to keep the 24 month lines (current and next year) short (PRODUCT_CATALOG has no such columns).
WITH PM AS (
  SELECT
    PRODUCT_ID,
    INITCAP(PRODUCT_FLOW_TYPE) AS FLOW,
    YEAR(MONTH_START) AS Y,
    TO_CHAR(MONTH_START, 'YYYY-MM') AS M,
    MAX(PRODUCT_DISPLAY_NAME) AS PRODUCT_DISPLAY_NAME,
    MAX(PROGRAM_NAME) AS PROGRAM_NAME,
    MAX(CUSTOMER_NAME) AS CUSTOMER_NAME,
    MAX(EMS_NAME) AS EMS_NAME,
    MAX(PLANNED_PRODUCT_UNITS) AS U,
    MAX(PLANNED_PRODUCT_UNITS)::NUMBER(38,2) AS Q
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_DEMAND_FORECAST
  GROUP BY PRODUCT_ID, INITCAP(PRODUCT_FLOW_TYPE), MONTH_START
)
SELECT
  PM.PRODUCT_ID::VARCHAR || '|' || PM.FLOW AS ROW_KEY,
  PM.PRODUCT_ID AS PRODUCT_ID,
  MAX(PM.PRODUCT_DISPLAY_NAME) AS PRODUCT_DISPLAY_NAME,
  MAX(C.PROJECT_NAME) AS PROJECT,
  MAX(PM.PROGRAM_NAME) AS PROGRAM,
  MAX(PM.CUSTOMER_NAME) AS CUSTOMER,
  MAX(PM.EMS_NAME) AS EMS,
  PM.FLOW AS FLOW
  {{SERIES: ,SUM(IFF(PM.Y=#YEAR#,PM.U,0))::NUMBER(38,2) AS UNITS_#YEAR# || ,SUM(IFF(M='#YEAR#-#MM#',Q,0)) AS M_#YEAR#_#MM#}}
FROM PM
LEFT JOIN MECL_PLATFORM.ANALYTICS.PRODUCT_CATALOG C ON C.PRODUCT_ID = PM.PRODUCT_ID
GROUP BY PM.PRODUCT_ID, PM.FLOW
