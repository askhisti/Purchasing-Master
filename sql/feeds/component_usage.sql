-- Component_Usage: one row per component x product from the demand forecast. Placeholder: {{BASE_YEAR}}.
WITH USAGE AS (
  SELECT
    PART_NUMBER,
    PRODUCT_ID,
    MAX(MPN) AS MPN,
    MAX(MANUFACTURER_NAME) AS MANUFACTURER_NAME,
    MAX(PRODUCT_DISPLAY_NAME) AS PRODUCT_DISPLAY_NAME,
    MAX(PROGRAM_NAME) AS PROGRAM_NAME,
    MAX(CUSTOMER_NAME) AS CUSTOMER_NAME,
    MAX(EMS_NAME) AS EMS_NAME,
    MAX(QTY_PER_UNIT) AS QTY_PER_UNIT,
    SUM(IFF(DEMAND_YEAR = {{BASE_YEAR}} + 0, DEMAND_QUANTITY, 0)) AS DEMAND_Y0,
    SUM(IFF(DEMAND_YEAR = {{BASE_YEAR}} + 1, DEMAND_QUANTITY, 0)) AS DEMAND_Y1,
    SUM(IFF(DEMAND_YEAR = {{BASE_YEAR}} + 2, DEMAND_QUANTITY, 0)) AS DEMAND_Y2,
    SUM(IFF(DEMAND_YEAR = {{BASE_YEAR}} + 3, DEMAND_QUANTITY, 0)) AS DEMAND_Y3,
    SUM(IFF(DEMAND_YEAR = {{BASE_YEAR}} + 4, DEMAND_QUANTITY, 0)) AS DEMAND_Y4,
    SUM(IFF(DEMAND_YEAR = {{BASE_YEAR}} + 5, DEMAND_QUANTITY, 0)) AS DEMAND_Y5,
    SUM(IFF(DEMAND_YEAR = {{BASE_YEAR}} + 6, DEMAND_QUANTITY, 0)) AS DEMAND_Y6,
    SUM(IFF(DEMAND_YEAR = {{BASE_YEAR}} + 7, DEMAND_QUANTITY, 0)) AS DEMAND_Y7,
    SUM(IFF(DEMAND_YEAR = {{BASE_YEAR}} + 8, DEMAND_QUANTITY, 0)) AS DEMAND_Y8,
    SUM(IFF(DEMAND_YEAR = {{BASE_YEAR}} + 9, DEMAND_QUANTITY, 0)) AS DEMAND_Y9,
    SUM(IFF(DEMAND_YEAR = {{BASE_YEAR}} + 10, DEMAND_QUANTITY, 0)) AS DEMAND_Y10
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_DEMAND_FORECAST
  WHERE IS_SOURCED_BY_US AND PART_KIND = 'COMPONENT'
  GROUP BY PART_NUMBER, PRODUCT_ID
),
PROJECTS AS (
  SELECT PART_NUMBER, PRODUCT_ID, MAX(PROJECT_NAME) AS PROJECT_NAME
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_WHERE_USED
  GROUP BY PART_NUMBER, PRODUCT_ID
)
SELECT
  U.PART_NUMBER || '|' || U.PRODUCT_ID AS ROW_KEY,
  U.PART_NUMBER AS ME_EC,
  U.MPN AS MPN,
  U.MANUFACTURER_NAME AS MANUFACTURER,
  U.PRODUCT_DISPLAY_NAME AS PRODUCT,
  U.PRODUCT_ID AS PRODUCT_ID,
  P.PROJECT_NAME AS PROJECT,
  U.PROGRAM_NAME AS PROGRAM,
  U.CUSTOMER_NAME AS CUSTOMER,
  U.EMS_NAME AS EMS,
  U.QTY_PER_UNIT::FLOAT AS QTY_PER_UNIT,
  U.DEMAND_Y0 AS DEMAND_Y0,
  U.DEMAND_Y1 AS DEMAND_Y1,
  U.DEMAND_Y2 AS DEMAND_Y2,
  U.DEMAND_Y3 AS DEMAND_Y3,
  U.DEMAND_Y4 AS DEMAND_Y4,
  U.DEMAND_Y5 AS DEMAND_Y5,
  U.DEMAND_Y6 AS DEMAND_Y6,
  U.DEMAND_Y7 AS DEMAND_Y7,
  U.DEMAND_Y8 AS DEMAND_Y8,
  U.DEMAND_Y9 AS DEMAND_Y9,
  U.DEMAND_Y10 AS DEMAND_Y10
FROM USAGE U
LEFT JOIN PROJECTS P ON P.PART_NUMBER = U.PART_NUMBER AND P.PRODUCT_ID = U.PRODUCT_ID
