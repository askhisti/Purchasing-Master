-- Component_Usage: one row per component x product from the demand forecast. Demand columns come from the DEMAND template, one per demand year.
WITH USAGE AS (
  SELECT
    PART_NUMBER,
    PRODUCT_ID,
    MAX(MPN) AS MPN,
    MAX(MANUFACTURER_NAME) AS MANUFACTURER_NAME,
    MAX(PRODUCT_DISPLAY_NAME) AS PRODUCT_DISPLAY_NAME,
    MAX(PROGRAM_NAME) AS PROGRAM_NAME,
    MAX(CUSTOMER_NAME) AS CUSTOMER_NAME,
    MAX(EMS_NAME) AS EMS_NAME,
    MAX(QTY_PER_UNIT) AS QTY_PER_UNIT
    {{DEMAND: , SUM(IFF(DEMAND_YEAR = #YEAR#, DEMAND_QUANTITY, 0)) AS DEMAND_#YEAR#}}
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_DEMAND_FORECAST
  WHERE IS_SOURCED_BY_US AND PART_KIND = 'COMPONENT'
  GROUP BY PART_NUMBER, PRODUCT_ID
),
PROJECTS AS (
  SELECT PART_NUMBER, PRODUCT_ID, MAX(PROJECT_NAME) AS PROJECT_NAME
  FROM MECL_PLATFORM.ANALYTICS.COMPONENT_WHERE_USED
  GROUP BY PART_NUMBER, PRODUCT_ID
)
SELECT
  U.PART_NUMBER || '|' || U.PRODUCT_ID AS ROW_KEY,
  U.PART_NUMBER AS ME_EC,
  U.MPN AS MPN,
  U.MANUFACTURER_NAME AS MANUFACTURER,
  U.PRODUCT_DISPLAY_NAME AS PRODUCT,
  U.PRODUCT_ID AS PRODUCT_ID,
  P.PROJECT_NAME AS PROJECT,
  U.PROGRAM_NAME AS PROGRAM,
  U.CUSTOMER_NAME AS CUSTOMER,
  U.EMS_NAME AS EMS,
  U.QTY_PER_UNIT::FLOAT AS QTY_PER_UNIT
  {{DEMAND: , U.DEMAND_#YEAR# AS DEMAND_#YEAR#}}
FROM USAGE U
LEFT JOIN PROJECTS P ON P.PART_NUMBER = U.PART_NUMBER AND P.PRODUCT_ID = U.PRODUCT_ID
