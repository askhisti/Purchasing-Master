-- Health gate: one row. Blocks on problems in the MECL snapshot area or on the feeds' source views.
SELECT
  YEAR(CONVERT_TIMEZONE('Europe/Berlin', CURRENT_TIMESTAMP())) AS BASE_YEAR,
  (SELECT COUNT(*)
     FROM MECL_PLATFORM.ANALYTICS.PLATFORM_HEALTH
    WHERE IS_PROBLEM
      AND (AREA LIKE 'MECL%'
           OR OBJECT_NAME IN ('COMPONENT_CATALOG', 'KPI_COMPONENT_DEMAND_BY_YEAR', 'MULTISOURCE_PARTS',
                              'MULTISOURCE_PART_MEMBERS', 'SC_EMS_PART', 'COMPONENT_DEMAND_FORECAST',
                              'COMPONENT_WHERE_USED', 'PRODUCT_CATALOG', 'COMPONENT_PRICE_ITEMS'))) AS PROBLEM_COUNT,
  (SELECT LISTAGG(AREA || '/' || OBJECT_NAME || ' (' || COALESCE(STATUS, '?') || ')', ', ') WITHIN GROUP (ORDER BY AREA, OBJECT_NAME)
     FROM MECL_PLATFORM.ANALYTICS.PLATFORM_HEALTH
    WHERE IS_PROBLEM
      AND (AREA LIKE 'MECL%'
           OR OBJECT_NAME IN ('COMPONENT_CATALOG', 'KPI_COMPONENT_DEMAND_BY_YEAR', 'MULTISOURCE_PARTS',
                              'MULTISOURCE_PART_MEMBERS', 'SC_EMS_PART', 'COMPONENT_DEMAND_FORECAST',
                              'COMPONENT_WHERE_USED', 'PRODUCT_CATALOG', 'COMPONENT_PRICE_ITEMS'))) AS PROBLEM_LIST,
  (SELECT MAX(REFRESHED_AT) FROM MECL_PLATFORM.ANALYTICS.SC_EMS_PART) AS REFRESHED_AT_SC_EMS_PART,
  (SELECT MAX(REFRESHED_AT) FROM MECL_PLATFORM.ANALYTICS.COMPONENT_WHERE_USED) AS REFRESHED_AT_COMPONENT_WHERE_USED
