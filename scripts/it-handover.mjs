// Usage: node scripts/it-handover.mjs [baseYear] [outDir]
// Writes the handover pack for a direct Snowflake export (docs/IT-HANDOVER.md): one ready-to-run SQL file per
// feed (placeholders rendered for baseYear), the health check as 00_health.sql, and manifest-template.json with each feed's tab, headers and types.
// Base year defaults to the current Berlin year; outDir defaults to handover/<baseYear>.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadManifest, demandYearsFor, demandMonthsFor, headersFor, sqlColumnsFor } from '../refresh/lib/manifest.mjs';
import { renderFeedSql } from '../refresh/lib/sql.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const [yearArg, dirArg] = process.argv.slice(2);
const baseYear = yearArg
  ? Number(yearArg)
  : Number(new Intl.DateTimeFormat('en-CA', { timeZone: 'Europe/Berlin', year: 'numeric' }).format(new Date()));
if (!Number.isInteger(baseYear)) {
  console.error('usage: node scripts/it-handover.mjs [baseYear] [outDir]');
  process.exit(2);
}
const outDir = path.resolve(root, dirArg || path.join('handover', String(baseYear)));
fs.mkdirSync(outDir, { recursive: true });

const typesFor = (f) => [
  ...f.columns.map((c) => c.type),
  ...headersFor(f, baseYear).slice(f.columns.length).map(() => 'number'),
];

fs.copyFileSync(path.join(root, 'sql', 'health.sql'), path.join(outDir, '00_health.sql'));
const feeds = [];
loadManifest().feeds.forEach((f, i) => {
  const text = fs.readFileSync(path.join(root, f.sqlFile), 'utf8');
  const sql = renderFeedSql(text, baseYear, demandYearsFor(f, baseYear), demandMonthsFor(f, baseYear)).trim().replace(/;\s*$/, '');
  const name = `${String(i + 1).padStart(2, '0')}_${f.feed}.sql`;
  const head = `-- Feed ${f.feed} -> tab ${f.tab}, base year ${baseYear}. Generated by scripts/it-handover.mjs; do not edit.\n`
    + '-- Column 1 is ROW_KEY (unique; drop it from the data file). The other columns are in sheet order.\n';
  fs.writeFileSync(path.join(outDir, name), `${head}${sql}\nORDER BY ROW_KEY;\n`);
  const headers = headersFor(f, baseYear);
  feeds.push({
    feed: f.feed, tab: f.tab, sqlFile: name,
    sqlColumns: sqlColumnsFor(f, baseYear), headers, types: typesFor(f),
    rowCount: '<rows in the data file>', file: `<runId>__${f.feed}.json.gz`, sha256: '<sha256 hex of the .json.gz bytes>',
  });
});

const template = {
  version: 1, runId: '<YYYY-MM-DDTHH-mm-ss, Berlin time>', status: 'ready', baseYear,
  startedAt: '<ISO 8601 UTC, export start>', publishedAt: '<ISO 8601 UTC, upload time>', health: null, feeds,
};
fs.writeFileSync(path.join(outDir, 'manifest-template.json'), `${JSON.stringify(template, null, 2)}\n`);
console.log(`wrote ${feeds.length} SQL files and manifest-template.json to ${path.relative(root, outDir)}`);
